"""GapM5 R2 original techno-pop score and desktop preview generator.

Arrangement: tight electronic pulse, syncopated octave bass, short jazz-voiced
poly chords and angular chromatic melody. No notes sampled or transcribed from
existing recordings. Embedded score and WAV preview share this exact sequence.
Usage: python tools/generate_music.py   # requires numpy for WAV preview
"""
from __future__ import annotations
import math
from pathlib import Path
import wave
import numpy as np

BASE = Path(__file__).resolve().parents[1]
# Eight bars / sixteen 16th-note steps per bar at ~134 BPM.
# | Em9 | A13 | Dmaj9 | B7b9 | Gmaj7 | F#7 | Bm9 | B7 |
BARS = [
    [76, 0, 0,79, 0, 0,78, 0, 0, 0,74, 0, 0, 0,76, 0],
    [73, 0,76, 0, 0, 0,79, 0, 0, 0,78, 0,73, 0, 0, 0],
    [78, 0, 0,76, 0, 0,74, 0, 0,73, 0, 0, 0,76, 0, 0],
    [75, 0,78, 0, 0, 0,81, 0, 0, 0,84, 0,83, 0,81, 0],
    [71, 0, 0,74, 0, 0,78, 0, 0, 0,79, 0, 0, 0,78, 0],
    [70, 0,73, 0, 0, 0,76, 0, 0, 0,82, 0, 0, 0,79, 0],
    [71, 0, 0,73, 0, 0,74, 0, 0, 0,78, 0,81, 0, 0, 0],
    [81, 0, 0,78, 0, 0,75, 0, 0, 0,78, 0,76, 0,75, 0],
]
ROOT = [52, 57, 50, 47, 55, 54, 47, 47]  # E3 A3 D3 B2 G3 F#3 B2 B2
SEVENTH = [10, 10, 11, 10, 11, 10, 10, 10]
BASS_PATTERN = [0,-1,12,-1,7,-1,12,-1,0,-1,10,-1,7,-1,12,-1]
CHORDS = [
    [67,74,78],   # Em9: G4 D5 F#5
    [67,71,78],   # A13: G4 B4 F#5
    [66,73,76],   # Dmaj9: F#4 C#5 E5
    [69,75,84],   # B7b9: A4 D#5 C6
    [66,71,74],   # Gmaj7: F#4 B4 D5
    [70,76,78],   # F#7: A#4 E5 F#5
    [69,73,74],   # Bm9: A4 C#5 D5
    [69,75,78],   # B7: A4 D#5 F#5
]
STEP_MS = 112


def arrays(rows):
    return ',\n'.join('  {'+', '.join(str(v) for v in row)+'}' for row in rows)


def write_header():
    txt = f'''// AUTOGENERATED by tools/generate_music.py; original composition for GapM5.
// 8-bar syncopated techno-pop. Root motion ii-V-I-VI, then IV-III7-vi-V7.
#pragma once
#include <cstdint>
namespace music_score {{
constexpr uint16_t STEP_MS={STEP_MS};
constexpr uint8_t LEAD[8][16]{{
{arrays(BARS)}
}};
constexpr uint8_t ROOT[8]{{{', '.join(map(str,ROOT))}}};
constexpr uint8_t SEVENTH[8]{{{', '.join(map(str,SEVENTH))}}};
constexpr int8_t BASS_PATTERN[16]{{{', '.join(map(str,BASS_PATTERN))}}};
constexpr uint8_t CHORDS[8][3]{{
{arrays(CHORDS)}
}};
}}
'''
    (BASE / 'src/music_score.hpp').write_text(txt, encoding='utf8')


def freq(m):
    return 440 * (2.0 ** ((m - 69) / 12))


def add_voice(buf, start, midi, duration, amp, kind='lead'):
    sr = 24000
    start = round(start*sr)
    n = min(len(buf)-start,round(duration*sr))
    if n <= 0: return
    t=np.arange(n,dtype=np.float64)/sr
    f=freq(midi)
    if kind=='lead':
        phase=2*np.pi*f*t + 0.11*np.sin(2*np.pi*5*t)
        sig = (np.sin(phase) + 0.30*np.sin(2*phase) + 0.16*np.sin(3*phase)) / 1.46
        env=np.minimum(1,t/.007)*np.minimum(1,(duration-t)/.085) * (.8+.2*np.exp(-t*8))
    elif kind=='bass':
        phase=2*np.pi*f*t + .5*np.exp(-t*30)*np.sin(2*np.pi*3*f*t)
        sig=.8*np.sin(phase)+.22*np.sin(2*phase)+.09*np.sin(3*phase)
        env=np.minimum(1,t/.004)*np.exp(-t*4.5)*np.minimum(1,(duration-t)/.035)
    elif kind=='chord':
        phase=2*np.pi*f*t
        saw=(2*np.mod(f*t,1)-1)
        saw2=(2*np.mod((f*1.004)*t+.2,1)-1)
        sig = (.46*saw + .44*saw2 + .28*np.sin(phase))
        env=np.minimum(1,t/.01)*np.exp(-t*7.3)*np.minimum(1,(duration-t)/.03)
    else: return
    buf[start:start+n] += amp*sig*np.maximum(0,env)


def add_drum(buf,start,kind,rng):
    sr=24000
    length = {'kick':.17,'snare':.13,'hat':.055}[kind]
    i=round(start*sr);n=min(len(buf)-i,round(sr*length))
    if n<=0:return
    t=np.arange(n)/sr
    if kind=='kick':
        phase=2*np.pi*(62*t + (72-62)*(.018/(2*np.pi))* (1-np.exp(-t/.018))*2*np.pi)
        x=.26*np.sin(phase)*np.exp(-t*24)+.09*rng.standard_normal(n)*np.exp(-t*85)
    elif kind=='snare':
        z=rng.standard_normal(n)
        high=z-np.convolve(z,np.ones(25)/25,'same')
        x=.115*high*np.exp(-t*24)+.07*np.sin(2*np.pi*177*t)*np.exp(-t*40)
    else:
        z=rng.standard_normal(n)
        high=z-np.convolve(z,np.ones(40)/40,'same')
        x=.066*high*np.exp(-t*75)
    buf[i:i+n]+=x


def write_preview():
    sr=24000; bars=16; length = bars*16*STEP_MS/1000+.35
    buf=np.zeros(round(length*sr),dtype=np.float64)
    rng=np.random.default_rng(8052026)
    for bar_index in range(bars):
        bar=bar_index%8
        for p in range(16):
            sec=(bar_index*16+p)*STEP_MS/1000
            m=BARS[bar][p]
            if m:
                add_voice(buf,sec,m,.093,.18,'lead')
            offset=BASS_PATTERN[p]
            if offset>=0:
                delta=SEVENTH[bar] if offset==10 else offset
                add_voice(buf,sec,ROOT[bar]+delta,.156,.25,'bass')
            if p in (2,10):
                for ci,m in enumerate(CHORDS[bar]):
                    add_voice(buf,sec,m,.119,.060,'chord')
            if p%4==0:
                add_drum(buf,sec,'kick',rng)
            if p in (4,12):
                add_drum(buf,sec,'snare',rng)
            if p in (2,6,10,14):
                add_drum(buf,sec,'hat',rng)
    # Subtle 1/8 delay on lead-shaped transients: no samples from recordings.
    delay=round(sr*.224)
    buf[delay:]+=.095*buf[:-delay].copy()
    fade=round(sr*.31)
    buf[-fade:]*=np.linspace(1,0,fade)
    peak=max(.55,np.max(np.abs(buf)))
    pcm=(np.clip(buf/peak*.80,-1,1)*32767).astype('<i2')
    target=BASE/'audio/GapM5_R2_TechnoPop_preview.wav'
    target.parent.mkdir(parents=True,exist_ok=True)
    with wave.open(str(target),'wb') as out:
        out.setnchannels(1);out.setsampwidth(2);out.setframerate(sr)
        out.writeframes(pcm.tobytes())
    print(f'Wrote {target}: {len(pcm)/sr:.2f}s / 24000 Hz mono')


if __name__=='__main__':
    write_header()
    write_preview()
